import pandas as pd
from sklearn import linear_model

df = pd.read_csv("/content/drive/MyDrive/pharmacy_sales_dataset.csv")

df.head()

print(df.isnull().sum())

# Shows rows where ANY column has a missing value
df[df.isna().any(axis=1)]

x = df[['Advertising_Spend','Foot_Traffic','Num_Prescriptions','Local_Population','Distance_to_Competitor_km','Store_Size_sqft',	'Staff_Count']]
y = df[['Monthly_Sales']]

df.head()

print(x)
print(y)

from sklearn import model_selection
x_train, x_test, y_train, y_test = model_selection.train_test_split(x, y, test_size=0.20)

from sklearn import linear_model
model = linear_model.LinearRegression()
model.fit(x_train, y_train)

model.predict(x_test)

model.score(x_test, y_test)

import matplotlib.pyplot as plt

from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
import numpy as np

# Make predictions
y_pred = model.predict(x_test)

# Evaluation metrics
mae = mean_absolute_error(y_test, y_pred)
mse = mean_squared_error(y_test, y_pred)
rmse = np.sqrt(mse)
r2 = r2_score(y_test, y_pred)

print("MAE:", mae)
print("MSE:", mse)
print("RMSE:", rmse)
print("R² Score:", r2)

y_pred = model.predict(x_test)

plt.scatter(y_test, y_pred)
plt.plot(y_test, y_test, color = 'red')
plt.xlabel('Actual Values',color = 'red')
plt.ylabel('Predicted Values',color = 'red')
plt.title('Actual vs. Predicted Values', color = 'red')
plt.show()

